/* eslint-disable @typescript-eslint/no-require-imports -- Build the runtime prompt from the canonical Markdown. */
const fs = require("node:fs");
const path = require("node:path");
const base = path.join(__dirname, "../src/lib/agent/prompts");
const prompt = fs.readFileSync(path.join(base, "system-prompt.md"), "utf8");
fs.writeFileSync(
  path.join(base, "system-prompt.ts"),
  `// Generated by npm run prompt:sync. Edit system-prompt.md, then sync.\nexport const systemPrompt = ${JSON.stringify(prompt)};\n`,
);
